-- ── Urban Outfitters Views ──────────────────────────────────
CREATE OR REPLACE VIEW URBAN_OUTFITTERS.V_PURCHASE_ORDERS AS
SELECT po.*, l.STORE_NAME, l.REGION, l.STATE,
    CASE WHEN po.IS_REPLACEMENT_850 THEN 'Replacement 850 (no 860s per URBN policy)' ELSE 'Original 850' END AS PO_TYPE_LABEL
FROM SPS_RETAIL_AI.SHARED.PURCHASE_ORDER po
JOIN SPS_RETAIL_AI.SHARED.LOCATION l ON po.SHIP_TO_LOCATION_ID = l.LOCATION_ID
WHERE po.RETAILER_ID = 'UO';

CREATE OR REPLACE VIEW URBAN_OUTFITTERS.V_WEEKLY_ACTIVITY AS
SELECT a.*, l.STORE_NAME, l.REGION AS STORE_REGION, l.STATE AS STORE_STATE,
    i.STYLE_NUMBER, i.COLOR_NAME, i.SIZE_NAME, i.BRAND_NAME, i.MSRP AS ITEM_MSRP,
    i.URBN_SHORT_SKU,
    xref.MAPPING_STATUS AS SKU_MAPPING_STATUS
FROM SPS_RETAIL_AI.SHARED.SPS_ACTIVITY a
JOIN SPS_RETAIL_AI.SHARED.LOCATION l ON a.LOCATION_ID = l.LOCATION_ID
JOIN SPS_RETAIL_AI.SHARED.ITEM i ON a.ITEM_ID = i.ITEM_ID
LEFT JOIN SPS_RETAIL_AI.URBAN_OUTFITTERS.SKU_CROSSWALK xref ON a.ITEM_ID = xref.ITEM_ID
WHERE a.RETAILER_ID = 'UO';
